        def add_entry(entry_date, desc, lines):
            # توليد رقم قيد فريد
            entry_no = f"TEST-{datetime.now().strftime('%Y%m%d%H%M%S%f')}"
            
            total_debit = sum(l[2] for l in lines)
            total_credit = sum(l[3] for l in lines)
            
            if abs(total_debit - total_credit) > 0.01:
                print(f"⚠️ القيد غير متوازن: {desc}")
                return
            
            cur = conn.execute("""
                INSERT INTO journal_entries 
                (entry_no, entry_date, reference_type, reference_no, description, status, created_by, total_debit, total_credit)
                VALUES (?, ?, 'TEST', 'TEST', ?, 'POSTED', 1, ?, ?)
            """, (entry_no, entry_date, desc, total_debit, total_credit))
            
            je_id = cur.lastrowid
            line_no = 1
            for acc_code, line_desc, debit, credit in lines:
                conn.execute("""
                    INSERT INTO journal_entry_lines 
                    (journal_entry_id, line_no, account_code, description, debit_amount, credit_amount)
                    VALUES (?, ?, ?, ?, ?, ?)
                """, (je_id, line_no, acc_code, line_desc, debit, credit))
                line_no += 1
            
            print(f"✅ {desc} (مدين: {total_debit:.2f} = دائن: {total_credit:.2f})")

